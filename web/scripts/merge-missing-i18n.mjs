import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', 'lib', 'i18n', 'locales');
const read = (f) => JSON.parse(fs.readFileSync(path.join(root, f + '.json'), 'utf8'));
const write = (f, data) =>
  fs.writeFileSync(path.join(root, f + '.json'), JSON.stringify(data, null, 2) + '\n', 'utf8');

/** 深合并：src 的键补进 dst（dst 已有的键不动），返回是否发生修改 */
function merge(dst, src) {
  let changed = false;
  for (const [k, v] of Object.entries(src)) {
    if (!(k in dst)) {
      dst[k] = v;
      changed = true;
    } else if (v && typeof v === 'object' && !Array.isArray(v) &&
               dst[k] && typeof dst[k] === 'object' && !Array.isArray(dst[k])) {
      if (merge(dst[k], v)) changed = true;
    }
  }
  return changed;
}

